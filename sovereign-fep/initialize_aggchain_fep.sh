#!/bin/bash

# AggchainFEP Initialize Function Call using Cast
# Private Key from create_rollup_parameters.json

# Set variables from configuration files
AGGCHAIN_FEP_ADDRESS="0x5063C4C4e5093b586e4F926333b8126eAf46Aa87"
PRIVATE_KEY="0x12d7de8621a77640c9241b2595ba78ce443d05e94090365ab3bb5e19df82c625"
RPC_URL=$(kurtosis port print cdk el-1-geth-lighthouse rpc)

# Parameters from create_rollup_parameters.json
TRUSTED_SEQUENCER="0x0318A80977AcEF01302CA8911164d597cE5804a4"
ADMIN="0xE34aaF64b29273B7D567FCFc40544c014EEe9970"
GAS_TOKEN_ADDRESS="0x0000000000000000000000000000000000000000"
TRUSTED_SEQUENCER_URL="http://localhost:8125"
NETWORK_NAME="sovereign-fep7"

# InitParams struct values
L2_BLOCK_TIME=1
ROLLUP_CONFIG_HASH="0x1111111111111111111111111111111111111111111111111111111111111111"
STARTING_OUTPUT_ROOT="0x1111111111111111111111111111111111111111111111111111111111111111"
STARTING_BLOCK_NUMBER=1
STARTING_TIMESTAMP=1759311672
SUBMISSION_INTERVAL=5
OPTIMISTIC_MODE_MANAGER="0xE34aaF64b29273B7D567FCFc40544c014EEe9970"
AGGREGATION_VKEY="0x1111111111111111111111111111111111111111111111111111111111111111"
RANGE_VKEY_COMMITMENT="0x1111111111111111111111111111111111111111111111111111111111111111"

# Aggchain specific parameters
USE_DEFAULT_VKEYS=false
USE_DEFAULT_SIGNERS=true
INIT_OWNED_AGGCHAIN_VKEY="0x6666666666666666666666666666666666666666666666666666666666666666"
INIT_AGGCHAIN_VKEY_SELECTOR="0x123d0001"
THRESHOLD=1

echo "Calling initialize function on AggchainFEP contract..."
echo "Contract Address: $AGGCHAIN_FEP_ADDRESS"
echo "Network: $NETWORK_NAME"

# Cast command to call initialize function
cast send \
    --rpc-url "$RPC_URL" \
    --private-key "$PRIVATE_KEY" \
    "$AGGCHAIN_FEP_ADDRESS" \
    "initialize((uint256,bytes32,bytes32,uint256,uint256,uint256,address,bytes32,bytes32),(address,string)[],uint256,bool,bool,bytes32,bytes4,address,address,address,string,string)" \
    "($L2_BLOCK_TIME,$ROLLUP_CONFIG_HASH,$STARTING_OUTPUT_ROOT,$STARTING_BLOCK_NUMBER,$STARTING_TIMESTAMP,$SUBMISSION_INTERVAL,$OPTIMISTIC_MODE_MANAGER,$AGGREGATION_VKEY,$RANGE_VKEY_COMMITMENT)" \
    "[]" \
    "$THRESHOLD" \
    "$USE_DEFAULT_VKEYS" \
    "$USE_DEFAULT_SIGNERS" \
    "$INIT_OWNED_AGGCHAIN_VKEY" \
    "$INIT_AGGCHAIN_VKEY_SELECTOR" \
    "$ADMIN" \
    "$TRUSTED_SEQUENCER" \
    "$GAS_TOKEN_ADDRESS" \
    "$TRUSTED_SEQUENCER_URL" \
    "$NETWORK_NAME"

echo "Initialize function call completed!"
